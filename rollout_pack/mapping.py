"""Render a rollout.json as a Mermaid workflow map.

Deterministic: lanes appear in file order, approval gates in the order the
rollout lists them, and every path ends at the single Live node.
"""

from pathlib import Path


def build_mermaid(data):
    business = str(data.get("business", "Business"))
    lanes = data.get("lanes") or []
    lines = ["flowchart TD"]
    lines.append(f'    B["{business}"]')
    lines.append('    LIVE["Live"]')
    for index, lane in enumerate(lanes, start=1):
        lane_id = f"L{index}"
        lines.append(f'    B --> {lane_id}["{lane.get("name", "?")}"]')
        previous = lane_id
        for gate_index, action in enumerate(
            lane.get("approval_required_for") or [], start=1
        ):
            gate_id = f"G{index}_{gate_index}"
            lines.append(f'    {previous} --> {gate_id}{{"Approval gate: {action}"}}')
            previous = gate_id
        lines.append(f"    {previous} --> LIVE")
    return "\n".join(lines)


def map_markdown(data):
    business = str(data.get("business", "Business"))
    return (
        f"# Workflow Map — {business}\n\n"
        "Generated by `rollout-pack map`. Diamonds are approval gates: "
        "nothing crosses one without the lane's human owner.\n\n"
        "```mermaid\n"
        + build_mermaid(data)
        + "\n```\n"
    )


def write_map(folder, data):
    """Write workflow-map.md into folder and return its Path."""
    path = Path(folder) / "workflow-map.md"
    path.write_text(map_markdown(data), encoding="utf-8")
    return path
